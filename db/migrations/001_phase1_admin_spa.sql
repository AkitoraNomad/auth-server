-- Phase 1: privileged admin SPA support.
--
-- This migration is intentionally additive and preserves existing rows.
-- Apply it once to an existing PostgreSQL database before starting the server:
--
--   psql "$DB" -f db/migrations/001_phase1_admin_spa.sql
--
-- Fresh databases can use db/postgres.sql, which already contains these columns.

BEGIN;

-- Older installations may predate auth_admin entirely (the role tables were
-- removed before this migration was introduced). Create it additively first.
CREATE TABLE IF NOT EXISTS auth.auth_admin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES auth.auth_user(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ
);

ALTER TABLE auth.auth_client
    ADD COLUMN IF NOT EXISTS is_public BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE auth.auth_client
    ADD COLUMN IF NOT EXISTS redirect_uris TEXT[] NOT NULL DEFAULT '{}';

ALTER TABLE auth.auth_client
    ADD COLUMN IF NOT EXISTS grant_types TEXT[] NOT NULL
        DEFAULT '{authorization_code,client_credentials,refresh_token,implicit}';

-- Existing clients keep their previous behaviour (all globally enabled grants),
-- while the admin client is seeded with the narrower authorization_code +
-- refresh_token set by the server.
UPDATE auth.auth_client
SET grant_types = '{authorization_code,client_credentials,refresh_token,implicit}'
WHERE grant_types IS NULL OR cardinality(grant_types) = 0;

-- Add the unique constraint only if no unique index/constraint already covers
-- user_id (fresh installations get it from db/postgres.sql).
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_index i
        JOIN pg_attribute a
          ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
        WHERE i.indrelid = 'auth.auth_admin'::regclass
          AND i.indisunique
          AND a.attname = 'user_id'
    ) THEN
        ALTER TABLE auth.auth_admin
            ADD CONSTRAINT auth_admin_user_id_key UNIQUE (user_id);
    END IF;
END
$$;

COMMIT;
